import type { Gender, ProductStatus, ProductType } from "./types";

export interface SeedProduct {
  slug: string;
  sku: string;
  name: string;
  brand: string;
  gender: Gender;
  family: string;
  concentration: string;
  description: string;
  story: string;
  top_notes: string[];
  heart_notes: string[];
  base_notes: string[];
  price_2: number;
  price_5: number;
  price_8: number;
  price_30: number;
  stock: number;
  status: ProductStatus;
  badge: string | null;
  bestseller: boolean;
  new_arrival: boolean;
  featured: boolean;
  rating: number;
  review_count: number;
  image: string;
  gallery: string[];
  collections: string[];
  type: ProductType;
  bundle_items: string[];
  cost_price: number;
}

type ProductInput = Omit<
  SeedProduct,
  "description" | "story" | "bundle_items" | "type" | "sku" | "cost_price"
> & {
  signature?: string;
  description?: string;
  story?: string;
  sku?: string;
  bundle_items?: string[];
  type?: ProductType;
  cost_price?: number;
};

const img = (id: string) => `/images/products/${id}.jpg`;
const ed = (id: string) => `/images/editorial/${id}.jpg`;

let counter = 0;

function product(input: ProductInput): SeedProduct {
  counter += 1;
  const top = input.top_notes;
  const base = input.base_notes;
  const description =
    input.description ??
    `${input.name} by ${input.brand} is a ${input.family.toLowerCase()} ${input.concentration.toLowerCase()} that opens with ${top[0]} and settles into ${base[0]}. ${input.signature ?? "A modern signature, made to be worn and remembered."}`;
  const story =
    input.story ??
    `Hand-decanted from a sealed, authentic bottle in our Mombasa atelier. ${input.name} is part of the ${input.brand} library — ${input.family.toLowerCase()}, considered, and made for the moments you want to be remembered in.`;
  return {
    ...input,
    sku: input.sku ?? `MDS-${String(counter).padStart(3, "0")}`,
    type: input.type ?? "perfume",
    description,
    story,
    bundle_items: input.bundle_items ?? [],
    gallery: input.gallery.length ? input.gallery : [input.image, ed("hero")],
    cost_price: input.cost_price ?? Math.round(input.price_30 * 0.44),
  };
}

